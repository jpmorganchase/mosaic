#!/usr/bin/env node
/**
 * Static-export route-handler / Server Action swapper.
 *
 * Next 16's `output: 'export'` collector refuses to emit App Router
 * `route.ts` handlers unless they declare `export const dynamic =
 * 'force-static'` as a **string literal** — a `process.env`-driven
 * ternary fails its AST check. Server Actions (`'use server'`
 * modules) aren't supported at all under `output: export`. So we
 * can't conditionally toggle either from inside the source files.
 *
 * This script implements a temporary file swap around `next build`:
 *
 *   apply  — back up each real file to `<file>.bak`, then overwrite
 *            the original with a stub.
 *   revert — restore from `<file>.bak` and delete the backup.
 */
import { writeFileSync, existsSync, renameSync, unlinkSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const __dirname = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(__dirname, '..');
const ROUTES = [
  {
    path: 'src/app/api/auth/[...nextauth]/route.ts',
    why: 'Authentication requires a server runtime; not available in a CDN-only static export.',
    catchAll: 'nextauth'
  },
  {
    path: 'src/app/api/content/live/route.ts',
    why: 'The live-reload SSE stream requires a long-lived Node runtime; not available in a static export.'
  },
  {
    path: 'src/app/api/revalidate/route.ts',
    why: 'There is no server cache to revalidate in a static export. Rebuild the site to refresh content.'
  }
];
const ACTIONS = [
  {
    path: 'src/app/[...route]/previewAction.ts',
    exports: ['compilePreview'],
    why: 'The MDX preview Server Action requires a server runtime; the content editor is not available in a static export.'
  },
  {
    path: 'src/app/[...route]/persistAction.ts',
    exports: ['persistContent'],
    why: 'The persist Server Action requires a server runtime; the content editor is not available in a static export.'
  }
];
function routeStub(route) {
  const catchAllExport = route.catchAll
    ? `\nexport function generateStaticParams() {\n  return [{ ${route.catchAll}: ['stub'] }];\n}\n`
    : '';
  return `// Auto-generated by scripts/static-export-route-stubs.mjs for MOSAIC_OUTPUT=export.
// The real handler lives in ${route.path}.bak during the export build.
// Restore via 'node scripts/static-export-route-stubs.mjs revert'.
export const dynamic = 'force-static';
${catchAllExport}
function stub() {
  return Response.json(
    {
      ok: false,
      error: 'route-not-available-in-static-export',
      message: ${JSON.stringify(route.why)}
    },
    { status: 501 }
  );
}
export const GET = stub;
export const POST = stub;
export const PUT = stub;
export const PATCH = stub;
export const DELETE = stub;
`;
}
function actionStub(action) {
  const exports = action.exports
    .map(
      name =>
        `export async function ${name}(..._args: any[]): Promise<any> {\n  throw new Error(${JSON.stringify(
          action.why
        )});\n}`
    )
    .join('\n\n');
  return `// Auto-generated by scripts/static-export-route-stubs.mjs for MOSAIC_OUTPUT=export.
// The real action lives in ${action.path}.bak during the export build.
// Restore via 'node scripts/static-export-route-stubs.mjs revert'.
//
// No 'use server' directive — Server Action modules are unsupported
// under output: export. The editor branch is unreachable in static
// builds anyway because auth() is stubbed and editing requires it.
${exports}
`;
}
function backupAndWrite(relPath, contents) {
  const abs = resolve(siteRoot, relPath);
  const bak = `${abs}.bak`;
  if (!existsSync(abs)) {
    console.warn(`[static-export-stubs] skip (missing): ${relPath}`);
    return;
  }
  if (existsSync(bak)) {
    console.warn(
      `[static-export-stubs] ${relPath}.bak already exists; assuming previous build crashed mid-run, reusing existing backup.`
    );
  } else {
    renameSync(abs, bak);
  }
  writeFileSync(abs, contents, 'utf8');
  console.log(`[static-export-stubs] stubbed ${relPath}`);
}
function apply() {
  for (const route of ROUTES) backupAndWrite(route.path, routeStub(route));
  for (const action of ACTIONS) backupAndWrite(action.path, actionStub(action));
}
function revertOne(relPath) {
  const abs = resolve(siteRoot, relPath);
  const bak = `${abs}.bak`;
  if (!existsSync(bak)) {
    console.warn(`[static-export-stubs] skip revert (no backup): ${relPath}`);
    return;
  }
  if (existsSync(abs)) unlinkSync(abs);
  renameSync(bak, abs);
  console.log(`[static-export-stubs] restored ${relPath}`);
}
function revert() {
  for (const route of ROUTES) revertOne(route.path);
  for (const action of ACTIONS) revertOne(action.path);
}
const cmd = process.argv[2];
if (cmd === 'apply') apply();
else if (cmd === 'revert') revert();
else {
  console.error('Usage: static-export-route-stubs.mjs <apply|revert>');
  process.exit(2);
}
