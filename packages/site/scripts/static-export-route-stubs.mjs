#!/usr/bin/env node
/**
 * Static-export route-handler swapper.
 *
 * Next 16's `output: 'export'` collector refuses to emit App Router
 * `route.ts` handlers unless they declare `export const dynamic =
 * 'force-static'` as a **string literal** — a `process.env`-driven
 * ternary fails its AST check. So we can't conditionally toggle the
 * behaviour from inside the source file itself.
 *
 * This script implements a temporary file swap around `next build`:
 *
 *   apply  — back up each real route file to `route.ts.bak`, then
 *            overwrite the original with a static stub (501 response
 *            + `dynamic = 'force-static'`).
 *   revert — restore from `route.ts.bak` and delete the backup.
 *
 * Drive it from package.json:
 *
 *   "build:static:file": "... apply && next build ... ; ... revert ..."
 *
 * Even if `next build` fails, `revert` will still run (note the `;`
 * separator and explicit re-invocation — see package.json).
 *
 * Routes covered:
 *   - app/api/auth/[...nextauth]/route.ts  — auth not usable in CDN deploy
 *   - app/api/content/preview/route.ts     — editor not usable in CDN deploy
 *   - app/api/revalidate/route.ts          — no server cache to revalidate
 *
 * If a new route handler is added that pulls in server-only deps
 * (next-auth, next/cache, dynamic APIs), add it to the ROUTES list
 * below or the export build will start failing.
 */
import { writeFileSync, existsSync, renameSync, unlinkSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(__dirname, '..');

const ROUTES = [
  {
    path: 'src/app/api/auth/[...nextauth]/route.ts',
    why: 'Authentication requires a server runtime; not available in a CDN-only static export.',
    // Catch-all (`[...nextauth]`) routes need `generateStaticParams` under
    // `output: export`, even when stubbed.
    catchAll: 'nextauth'
  },
  {
    path: 'src/app/api/content/preview/route.ts',
    why: 'The MDX preview endpoint requires a server runtime; the content editor is not available in a static export.'
  },
  {
    path: 'src/app/api/content/live/route.ts',
    why: 'The live-reload SSE stream requires a long-lived Node runtime; not available in a static export.'
  },
  {
    path: 'src/app/api/revalidate/route.ts',
    why: 'There is no server cache to revalidate in a static export. Rebuild the site to refresh content.'
  }
];

function stubFor(route) {
  const catchAllExport = route.catchAll
    ? `
// Catch-all route — Next requires generateStaticParams under output: export.
// Emit a single placeholder param so the file is collectable; the handler
// always returns 501 anyway.
export function generateStaticParams() {
  return [{ ${route.catchAll}: ['stub'] }];
}
`
    : '';
  return `// Auto-generated by scripts/static-export-route-stubs.mjs for MOSAIC_OUTPUT=export.
// The real handler lives in ${route.path}.bak during the export build.
// Restore via 'node scripts/static-export-route-stubs.mjs revert'.

export const dynamic = 'force-static';
${catchAllExport}
function stub() {
  return Response.json(
    {
      ok: false,
      error: 'route-not-available-in-static-export',
      message: ${JSON.stringify(route.why)}
    },
    { status: 501 }
  );
}

export const GET = stub;
export const POST = stub;
export const PUT = stub;
export const PATCH = stub;
export const DELETE = stub;
`;
}

function apply() {
  for (const route of ROUTES) {
    const abs = resolve(siteRoot, route.path);
    const bak = `${abs}.bak`;
    if (!existsSync(abs)) {
      console.warn(`[static-export-stubs] skip (missing): ${route.path}`);
      continue;
    }
    if (existsSync(bak)) {
      // A previous run didn't revert cleanly. Trust the .bak as source
      // of truth (it's the unmodified original) and overwrite the
      // current file rather than back up the already-stubbed copy.
      console.warn(
        `[static-export-stubs] ${route.path}.bak already exists; assuming previous build crashed mid-run, reusing existing backup.`
      );
    } else {
      renameSync(abs, bak);
    }
    writeFileSync(abs, stubFor(route), 'utf8');
    console.log(`[static-export-stubs] stubbed ${route.path}`);
  }
}

function revert() {
  for (const route of ROUTES) {
    const abs = resolve(siteRoot, route.path);
    const bak = `${abs}.bak`;
    if (!existsSync(bak)) {
      console.warn(`[static-export-stubs] skip revert (no backup): ${route.path}`);
      continue;
    }
    if (existsSync(abs)) unlinkSync(abs);
    renameSync(bak, abs);
    console.log(`[static-export-stubs] restored ${route.path}`);
  }
}

const cmd = process.argv[2];
if (cmd === 'apply') apply();
else if (cmd === 'revert') revert();
else {
  console.error('Usage: static-export-route-stubs.mjs <apply|revert>');
  process.exit(2);
}
